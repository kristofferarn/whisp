import AppKit
import Carbon.HIToolbox

/**
 * Puts text into whatever has focus, by way of the clipboard: snapshot what
 * is there, put the transcript there (marked transient, so clipboard
 * managers don't keep every dictation), send ⌘V, then put the snapshot back.
 * Unlike typing it out character by character, this handles any length and
 * any characters in one go.
 *
 * If the paste can't happen, the transcript stays on the clipboard as an
 * ordinary entry and the error says so — a ⌘V away is better than lost.
 */
final class Inserter {
    enum Failure: LocalizedError {
        case noAccessibility, secureInput
        var errorDescription: String? {
            switch self {
            case .noAccessibility: "whisp can't paste without Accessibility — text is on the clipboard"
            case .secureInput: "A password field is blocking paste — text is on the clipboard"
            }
        }
    }

    /** How long the target app gets to read the clipboard before it is restored. */
    private static let restoreDelay: Duration = .milliseconds(400)

    func paste(_ text: String) async throws {
        let board = NSPasteboard.general
        if !AXIsProcessTrusted() || IsSecureEventInputEnabled() {
            board.clearContents()
            board.setString(text, forType: .string)
            throw AXIsProcessTrusted() ? Failure.secureInput : Failure.noAccessibility
        }

        let snapshot = Self.snapshot(board)
        board.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // nspasteboard.org conventions, honored by clipboard managers.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        board.writeObjects([item])
        let ours = board.changeCount

        Self.postCommandV()
        try? await Task.sleep(for: Self.restoreDelay)

        // Someone copied something in the meantime: theirs wins.
        guard board.changeCount == ours else { return }
        board.clearContents()
        if !snapshot.isEmpty { board.writeObjects(snapshot) }
    }

    private static func snapshot(_ board: NSPasteboard) -> [NSPasteboardItem] {
        (board.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    /**
     * ⌘V from a private event source, so a modifier physically held right
     * now (the dictation key itself, mid-next-take) doesn't ride along.
     */
    private static func postCommandV() {
        let source = CGEventSource(stateID: .privateState)
        let v = CGKeyCode(kVK_ANSI_V)
        for keyDown in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: keyDown) else { continue }
            event.flags = .maskCommand
            event.setIntegerValueField(.eventSourceUserData, value: Hotkey.syntheticMarker)
            event.post(tap: .cghidEventTap)
        }
    }
}
